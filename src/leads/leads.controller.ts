import {
  Controller,
  Get,
  Post,
  Body,
  Patch,
  Param,
  Delete,
  Request,
} from '@nestjs/common';
import { LeadsService, NewLeadDetails } from './leads.service';
import { LeadSnapshotService } from './lead-snapshot.service';
import { Prisma } from '@prisma/client';

@Controller('leads')
export class LeadsController {
  constructor(
    private readonly leadsService: LeadsService,
    private readonly leadSnapshotService: LeadSnapshotService,
  ) {}

  @Post()
  async create(
    @Body() body: Prisma.LeadCreateInput & NewLeadDetails,
    @Request() req: { user: { id: string } },
  ) {
    const { location, contacts, howWeMet, businessCardAttachmentIds, ...lead } =
      body;
    return this.leadsService.create(lead, req.user.id, {
      location,
      contacts,
      howWeMet,
      businessCardAttachmentIds,
    });
  }

  @Get()
  findAll() {
    return this.leadsService.findAll();
  }

  // Leads that have not been contacted at all
  @Get('new')
  findNewUncoctactedLeads() {
    return this.leadsService.findNewUncoctactedLeads();
  }

  // Leads that have been visited in person and now require immediate follow-up
  @Get('post-visit')
  findPostVisitLeads() {
    return this.leadsService.findPostVisitLeads();
  }

  // Leads that have not been contacted in 7 days or more
  @Get('estranged')
  findEstrangedLeads() {
    return this.leadsService.findEstrangedLeads();
  }

  @Get(':id')
  findOne(@Param('id') id: string) {
    return this.leadsService.findOne(id);
  }

  // AI summary of the lead's current state, generated by pitchr-ai
  @Get(':id/snapshot')
  getSnapshot(@Param('id') id: string) {
    return this.leadSnapshotService.getSnapshot(id);
  }

  @Patch(':id')
  update(
    @Param('id') id: string,
    @Body() updateLeadDto: Prisma.LeadUpdateInput,
    @Request() req: { user: { id: string } },
  ) {
    return this.leadsService.update(id, updateLeadDto, req.user.id);
  }

  @Delete(':id')
  remove(@Param('id') id: string) {
    return this.leadsService.remove(id);
  }
}
